export function createCodingEnvironmentPrompt(
  workspaceRoot: string,
  shell: SessionShell,
  permissionMode: PermissionMode,
): string {
  return [
    "当前工作区：" + workspaceRoot,
    "当前平台：" + process.platform,
    "固定 Shell：" + [shell.executable, ...shell.arguments].join(" "),
    "当前权限模式：" +
      (permissionMode === "full_access"
        ? "Full Access"
        : permissionMode === "auto_allow"
          ? "AutoAllow"
          : permissionMode === "plan"
            ? "Plan"
            : "Agent") +
      " 模式。",
    permissionMode === "plan"
      ? "任务工作区仅允许检查与分析；受管记忆维护属于 Anthias 应用数据。"
      : permissionMode === "full_access"
        ? "已跳过人工与模型审批，可访问工作区外文件；仍须遵守用户任务范围、应用数据保护与系统破坏硬限制，没有 OS 沙箱。"
        : "副作用按当前运行时权限和审批执行。",
  ].join("\n");
}
